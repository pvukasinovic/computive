# ---------------------------------------------------------------------------
# Top-level FSM (FSM next-state, regs, counters — opaque raw block)
# ---------------------------------------------------------------------------


def _add_top_fsm(mod: RTLModule) -> None:
    mod.add_raw(
        code=(
            "// FSM next-state\n"
            "always_comb begin\n"
            "    state_next = state;\n"
            "    case (state)\n"
            "        S_IDLE:       if (ctrl_start) state_next = S_RECV_IN;\n"
            "        S_RECV_IN:    if (axis_in_done) state_next = S_RUN_LAYER;\n"
            "        S_RUN_LAYER:  if (layer_done_sig) state_next = S_NEXT_LAYER;\n"
            "        S_NEXT_LAYER: begin\n"
            "            if (layer_idx == NUM_LAYERS - 1)\n"
            "                state_next = S_SEND_OUT;\n"
            "            else\n"
            "                state_next = S_RUN_LAYER;\n"
            "        end\n"
            "        S_SEND_OUT:   if (axis_out_done) state_next = S_DONE;\n"
            "        S_DONE:       state_next = S_IDLE;\n"
            "        default:      state_next = S_IDLE;\n"
            "    endcase\n"
            "end\n"
            "\n"
            "// State register\n"
            "always_ff @(posedge clk) begin\n"
            "    if (!rst_n || ctrl_soft_rst)\n"
            "        state <= S_IDLE;\n"
            "    else\n"
            "        state <= state_next;\n"
            "end\n"
            "\n"
            "// Layer index\n"
            "always_ff @(posedge clk) begin\n"
            "    if (!rst_n || state == S_IDLE)\n"
            "        layer_idx <= 16'b0;\n"
            "    else if (state == S_NEXT_LAYER)\n"
            "        layer_idx <= layer_idx + 1;\n"
            "end\n"
            "\n"
            "// Control signal generation\n"
            "assign axis_in_enable  = (state == S_RECV_IN);\n"
            "assign axis_out_enable = (state == S_SEND_OUT);\n"
            "assign layer_start     = (state == S_NEXT_LAYER) || "
            "(state == S_RECV_IN && axis_in_done);\n"
            "\n"
            "// Status\n"
            "assign status_idle = (state == S_IDLE);\n"
            "assign status_busy = (state != S_IDLE && state != S_DONE);\n"
            "assign status_error = 1'b0;\n"
            "assign error_code_reg = 32'b0;\n"
            "\n"
            "// Done and interrupt\n"
            "always_ff @(posedge clk) begin\n"
            "    if (!rst_n || state == S_IDLE) begin\n"
            "        status_done_reg <= 1'b0;\n"
            "        irq_done_pulse  <= 1'b0;\n"
            "    end else if (state == S_DONE) begin\n"
            "        status_done_reg <= 1'b1;\n"
            "        irq_done_pulse  <= 1'b1;\n"
            "    end else begin\n"
            "        irq_done_pulse <= 1'b0;\n"
            "    end\n"
            "end\n"
            "\n"
            "assign irq_error_pulse = 1'b0;\n"
            "\n"
            "// Cycle counter\n"
            "always_ff @(posedge clk) begin\n"
            "    if (!rst_n || state == S_IDLE) begin\n"
            "        cycle_counter <= 32'b0;\n"
            "        counting <= 1'b0;\n"
            "    end else if (state == S_RECV_IN && !counting) begin\n"
            "        counting <= 1'b1;\n"
            "        cycle_counter <= 32'b0;\n"
            "    end else if (counting && state != S_DONE) begin\n"
            "        cycle_counter <= cycle_counter + 1;\n"
            "    end\n"
            "end\n"
            "\n"
            "assign cycle_count_reg = cycle_counter;\n"
            "\n"
            "// Inference counter\n"
            "always_ff @(posedge clk) begin\n"
            "    if (!rst_n)\n"
            "        inf_count_reg <= 32'b0;\n"
            "    else if (state == S_DONE && state_next == S_IDLE)\n"
            "        inf_count_reg <= inf_count_reg + 1;\n"
            "end"
        ),
        defines=(
            "state",
            "state_next",
            "layer_idx",
            "axis_in_enable",
            "axis_out_enable",
            "layer_start",
            "status_idle",
            "status_busy",
            "status_error",
            "error_code_reg",
            "status_done_reg",
            "irq_done_pulse",
            "irq_error_pulse",
            "cycle_counter",
            "counting",
            "cycle_count_reg",
            "inf_count_reg",
        ),
        uses=(
            "ctrl_start",
            "ctrl_soft_rst",
            "axis_in_done",
            "axis_out_done",
            "layer_done_sig",
            "rst_n",
            "clk",
        ),
        label="Top-level FSM, status, counters",
    )


