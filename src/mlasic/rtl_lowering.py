def _add_sram_instances(mod: RTLModule, parallelism: int) -> None:
    p = parallelism

    mod.add_instance(
        name="weight_bank",
        module_type="sram_bank",
        params={
            "DEPTH": "WEIGHT_DEPTH",
            "WIDTH": f"{p}*8",
            "INIT_FILE": '"weight_bank.mem"',
        },
        port_map={
            "clk": "clk",
            "addr": "weight_addr[$clog2(WEIGHT_DEPTH)-1:0]",
            "we": "1'b0",
            "wdata": "{" + f"{p}*8{{1'b0}}" + "}",
            "rdata": "weight_rdata",
        },
        comment="Unified weight bank",
    )

    mod.add_instance(
        name="bias_bank",
        module_type="sram_bank",
        params={
            "DEPTH": "BIAS_DEPTH",
            "WIDTH": f"{p}*32",
            "INIT_FILE": '"bias_bank.mem"',
        },
        port_map={
            "clk": "clk",
            "addr": "bias_addr[$clog2(BIAS_DEPTH)-1:0]",
            "we": "1'b0",
            "wdata": "{" + f"{p}*32{{1'b0}}" + "}",
            "rdata": "bias_rdata",
        },
        comment="Bias bank",
    )

    # Activation ping-pong buffers (A and B)
    L = RTLType.logic
    for sig in ("act_a_addr", "act_b_addr"):
        mod.add_signal(sig, L(width="$clog2(ACT_DEPTH)"))
    for sig in ("act_a_we", "act_b_we"):
        mod.add_signal(sig, L())
    for sig in ("act_a_wdata", "act_b_wdata", "act_a_rdata", "act_b_rdata"):
        mod.add_signal(sig, L(width="AXI_DATA_W"))

    mod.add_instance(
        name="act_a",
        module_type="sram_bank",
        params={"DEPTH": "ACT_DEPTH", "WIDTH": "AXI_DATA_W"},
        port_map={
            "clk": "clk",
            "addr": "act_a_addr",
            "we": "act_a_we",
            "wdata": "act_a_wdata",
            "rdata": "act_a_rdata",
        },
    )
    mod.add_instance(
        name="act_b",
        module_type="sram_bank",
        params={"DEPTH": "ACT_DEPTH", "WIDTH": "AXI_DATA_W"},
        port_map={
            "clk": "clk",
            "addr": "act_b_addr",
            "we": "act_b_we",
            "wdata": "act_b_wdata",
            "rdata": "act_b_rdata",
        },
    )


def _add_activation_mux(mod: RTLModule) -> None:
    mod.add_assign(
        "input_bank_sel", "layer_idx[0]", comment="bank select from layer index"
    )

    mod.add_raw(
        code=(
            "always_comb begin\n"
            "    if (state == S_RECV_IN) begin\n"
            "        // AXI-Stream input writes to bank A\n"
            "        act_a_addr = axis_in_addr;\n"
            "        act_a_we = axis_in_we;\n"
            "        act_a_wdata = axis_in_wdata;\n"
            "        act_b_addr = {$clog2(ACT_DEPTH){1'b0}};\n"
            "        act_b_we = 1'b0;\n"
            "        act_b_wdata = {AXI_DATA_W{1'b0}};\n"
            "    end else if (state == S_SEND_OUT) begin\n"
            "        // AXI-Stream output reads from bank A (last layer)\n"
            "        act_a_addr = axis_out_addr;\n"
            "        act_a_we = 1'b0;\n"
            "        act_a_wdata = {AXI_DATA_W{1'b0}};\n"
            "        act_b_addr = {$clog2(ACT_DEPTH){1'b0}};\n"
            "        act_b_we = 1'b0;\n"
            "        act_b_wdata = {AXI_DATA_W{1'b0}};\n"
            "    end else if (!input_bank_sel) begin\n"
            "        // Read from A, write to B\n"
            "        act_a_addr = act_rd_addr;\n"
            "        act_a_we = 1'b0;\n"
            "        act_a_wdata = {AXI_DATA_W{1'b0}};\n"
            "        act_b_addr = act_wr_addr;\n"
            "        act_b_we = act_wr_en;\n"
            "        act_b_wdata = act_wr_data;\n"
            "    end else begin\n"
            "        // Read from B, write to A\n"
            "        act_b_addr = act_rd_addr;\n"
            "        act_b_we = 1'b0;\n"
            "        act_b_wdata = {AXI_DATA_W{1'b0}};\n"
            "        act_a_addr = act_wr_addr;\n"
            "        act_a_we = act_wr_en;\n"
            "        act_a_wdata = act_wr_data;\n"
            "    end\n"
            "end"
        ),
        defines=(
            "act_a_addr",
            "act_a_we",
            "act_a_wdata",
            "act_b_addr",
            "act_b_we",
            "act_b_wdata",
        ),
        uses=(
            "state",
            "axis_in_addr",
            "axis_in_we",
            "axis_in_wdata",
            "axis_out_addr",
            "input_bank_sel",
            "act_rd_addr",
            "act_wr_addr",
            "act_wr_en",
            "act_wr_data",
        ),
        label="Activation bank mux",
    )

    mod.add_assign(
        "act_rd_data", "input_bank_sel ? act_b_rdata : act_a_rdata"
    )
    mod.add_assign("axis_out_rdata", "act_a_rdata")


